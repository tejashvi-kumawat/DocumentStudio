const recipeMd = r'''# Paneer Butter Masala
*Serves 4 · Prep 15 min · Cook 25 min*

---

## Ingredients
- 250 g paneer, cubed
- 2 tbsp butter + 1 tbsp oil
- 1 large onion, chopped
- 3 tomatoes, puréed
- 10 cashews, soaked
- 1 tbsp ginger-garlic paste
- 1 tsp Kashmiri chilli powder, ½ tsp garam masala, salt to taste
- 3 tbsp fresh cream, 1 tsp kasuri methi

## Method
1. Heat oil and 1 tbsp butter; sauté the onion until golden.
2. Add ginger-garlic paste; cook 1 minute.
3. Add tomato purée and cashews; simmer 10 minutes, then blend smooth.
4. Return to the pan, add the spices and ½ cup water; simmer 5 minutes.
5. Add paneer, cream and kasuri methi; finish with the remaining butter.

> **Tip:** Soak the paneer in hot water for 10 minutes so it stays soft.

## Nutrition (per serving)
| Calories | Protein | Fat | Carbs |
|---------:|--------:|----:|------:|
| 420 kcal | 16 g | 32 g | 14 g |
''';

