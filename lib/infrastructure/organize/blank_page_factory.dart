/// Cached blank single-page PDF on disk for workspace insert/export.
class BlankPageFactory {
  BlankPageFactory(this._storage);

  final FileStoragePort _storage;
  LocalFileRef? _cached;

  Future<LocalFileRef> blankPageFile() async {
    if (_cached != null && await _storage.fileExists(_cached!)) {
      return _cached!;
    }
    final dir = await _storage.getAppSupportDirectory();
    final path = p.join(dir, 'document_studio_blank_page.pdf');
    final file = File(path);
    if (!await file.exists()) {
      await file.writeAsBytes(_kBlankPdfBytes, flush: true);
    }
    final stat = await file.stat();
    _cached = LocalFileRef(
      path: path,
      displayName: 'Blank page',
      sizeBytes: stat.size,
      lastModified: stat.modified,
    );
    return _cached!;
  }
}
